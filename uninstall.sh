#!/usr/bin/env bash
# ============================================================
#  УДАЛЕНИЕ «КНИЖНОГО СТРАЖА» (Linux / macOS)
#  Удаление возможно ТОЛЬКО по паролю.
#  Что удаляется: программа, резервная копия «стража»,
#  автозапуск (приложение + страж), ярлыки, сама защита.
# ============================================================
cd "$(dirname "$0")"
echo "============================================================"
echo "  УДАЛЕНИЕ «КНИЖНОГО СТРАЖА»"
echo "============================================================"
echo
if [ -x .venv/bin/python ]; then PY=.venv/bin/python; else PY=python3; fi
"$PY" -m bookguard uninstall --yes
rc=$?
if [ $rc -ne 0 ]; then
  echo
  echo "[x] Удаление не завершено (неверный пароль или ошибка)."
  echo "    Если программа уже повреждена - удалите папку вручную."
  exit 1
fi
echo
echo "============================================================"
echo "  УДАЛЕНО. Спасибо, что использовали «Книжный страж»!"
echo "============================================================"
echo " Файлы удалятся через несколько секунд (процесс уже выключен)."
sleep 7
exit 0
